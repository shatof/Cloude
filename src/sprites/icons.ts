/** Colore une icône d'interface (« x » → couleur de la palette), pour en faire une icône de carte. */
export function tint(sprite: Sprite, color: string): Sprite {
  return { ...sprite, rows: sprite.rows.map((r) => r.replace(/x/g, color)) };
}

