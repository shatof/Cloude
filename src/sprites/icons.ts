/** Icône d'une pièce de harnais : icône dédiée, sinon calque recadré. */
export function pieceIcon(pieceId: string): Sprite | undefined {
  const layers = PIECE_LAYERS[pieceId];
  if (!layers) return undefined;
  if (layers.icon) return layers.icon;
  const source = layers.front ?? layers.back;
  if (!source) return undefined;
  const b = spriteBounds(source);
  if (!b) return undefined;
  const size = Math.max(b.w, b.h);
  return cropSprite(source, b.x - Math.floor((size - b.w) / 2), b.y - Math.floor((size - b.h) / 2), size, size);
}

